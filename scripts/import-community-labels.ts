/**
 * Builds protocols/community-labels.json from the third-party snapshot in
 * protocols/sources: display names only, attributed and marked unverified.
 *
 *   node scripts/import-community-labels.ts
 *
 * Rules (see protocols/sources/README.md):
 * - Only the `program` and `address` sections. `hacker` attributions are third-party
 *   verdicts, which FraudWatch never imports; `trust_token` isn't an address list.
 * - Addresses already in the verified registry are skipped: the registry wins.
 * - Every key must be a valid Solana address; names are trimmed and blank ones dropped.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { isAddress } from "@solana/kit";

const SOURCE = "protocols/sources/tribixbite-solana-programs.json";
const OUT = "protocols/community-labels.json";
const REGISTRY_FILES = ["protocols/solana.json", "protocols/centralized-vaults.json"];

type RegistryFile = { protocols: Record<string, { addresses: Record<string, unknown> }> };
type Snapshot = Record<string, Record<string, string>>;

const verified = new Set<string>();
for (const file of REGISTRY_FILES) {
  const json = JSON.parse(readFileSync(file, "utf8")) as RegistryFile;
  for (const protocol of Object.values(json.protocols)) for (const address of Object.keys(protocol.addresses)) verified.add(address);
}

const snapshot = JSON.parse(readFileSync(SOURCE, "utf8")) as Snapshot;
const labels: Record<string, string> = {};
const skipped = { verified: 0, invalid: 0, blank: 0 };
for (const section of ["program", "address"]) {
  for (const [rawAddress, rawName] of Object.entries(snapshot[section] ?? {})) {
    const address = rawAddress.trim();
    const name = rawName.trim().replace(/\s+/g, " ");
    if (!isAddress(address)) skipped.invalid++;
    else if (!name) skipped.blank++;
    else if (verified.has(address)) skipped.verified++;
    else if (!(address in labels)) labels[address] = name;
  }
}

const sorted = Object.fromEntries(Object.entries(labels).sort(([a], [b]) => a.localeCompare(b)));
writeFileSync(
  OUT,
  JSON.stringify(
    {
      source: "tribixbite solana-programs gist",
      sourceUrl: "https://gist.github.com/tribixbite/9a7f0a45e41c2f9cf64428f900a25c5b",
      revision: "35cb2e3604ff685ebd4712283c16d07258ee5f7d",
      note: "Third-party display names, not verified by FraudWatch. Generated by scripts/import-community-labels.ts; edit the source or the script, not this file.",
      labels: sorted,
    },
    null,
    2,
  ) + "\n",
);
console.log(`${Object.keys(sorted).length} labels written to ${OUT}; skipped ${skipped.verified} already verified, ${skipped.invalid} invalid, ${skipped.blank} blank.`);
